// ===== Computed Statistics =====
function computeRiauStats() {
  const n = RIAU_POINTS.length;
  let sumDryDays = 0, sumLstMax = 0, sumRainfall = 0, sumMeanLst = 0, sumNdvi = 0, sumTotalRain = 0;
  let minDry = Infinity, maxDry = -Infinity;
  let critical = 0, high = 0, moderate = 0, low = 0;
  
  const dryDaysBins = {};
  const rainfallBins = {};
  
  RIAU_POINTS.forEach(p => {
    const [lat, lon, dryDays, lstMax, meanRain, meanLst, minNdvi, totalRain] = p;
    sumDryDays += dryDays;
    sumLstMax += lstMax;
    sumRainfall += meanRain;
    sumMeanLst += meanLst;
    sumNdvi += minNdvi;
    sumTotalRain += totalRain;
    
    if (dryDays < minDry) minDry = dryDays;
    if (dryDays > maxDry) maxDry = dryDays;
    
    // Risk classification based on Field et al. (2016):
    // Critical: dry days >= 90 AND mean rainfall < 3mm/day
    // High: dry days >= 80 OR (dry days >= 70 AND mean rainfall < 4mm/day)
    // Moderate: dry days >= 60 AND mean rainfall < 5mm/day
    // Low: everything else
    if (dryDays >= 90 && meanRain < 3) {
      critical++;
    } else if (dryDays >= 80 || (dryDays >= 70 && meanRain < 4)) {
      high++;
    } else if (dryDays >= 60 && meanRain < 5) {
      moderate++;
    } else {
      low++;
    }
    
    // Bin dry days
    const dryBin = Math.floor(dryDays / 10) * 10;
    dryDaysBins[dryBin] = (dryDaysBins[dryBin] || 0) + 1;
    
    // Bin rainfall
    const rainBin = Math.floor(meanRain);
    rainfallBins[rainBin] = (rainfallBins[rainBin] || 0) + 1;
  });
  
  return {
    count: n,
    avgDryDays: (sumDryDays / n).toFixed(1),
    avgLstMax: (sumLstMax / n).toFixed(1),
    avgRainfall: (sumRainfall / n).toFixed(2),
    avgMeanLst: (sumMeanLst / n).toFixed(1),
    avgNdvi: (sumNdvi / n).toFixed(3),
    avgTotalRain: (sumTotalRain / n).toFixed(0),
    minDryDays: minDry,
    maxDryDays: maxDry,
    riskCounts: { critical, high, moderate, low },
    dryDaysBins,
    rainfallBins
  };
}

const RIAU_STATS = computeRiauStats();

// Risk color function
function getRiskLevel(dryDays, meanRain) {
  if (dryDays >= 90 && meanRain < 3) return { level: 'critical', color: '#dc2626', label: 'Kritis' };
  if (dryDays >= 80 || (dryDays >= 70 && meanRain < 4)) return { level: 'high', color: '#f97316', label: 'Tinggi' };
  if (dryDays >= 60 && meanRain < 5) return { level: 'moderate', color: '#f59e0b', label: 'Sedang' };
  return { level: 'low', color: '#22c55e', label: 'Rendah' };
}
